export default function WhyEncryptYourLetters() {
  return (
    <>
      <p>
        We tend to think of encryption as something banks and governments do. Something
        serious and technical, with threat models and adversaries. Most personal apps
        don't bother. Your notes app, your journal, your "send-to-future-self" service —
        they all read your messages, in plaintext, on their servers.
      </p>

      <p>
        That's the default. And the default is wrong.
      </p>

      <h2>Why your letters deserve the same protection as your money</h2>

      <p>
        We've collectively decided that our financial information deserves to be
        encrypted. We use VPNs, we use Signal, we use hardware wallets. But we write
        our most honest thoughts in apps that store them in plaintext. Apps that can be
        breached. Apps that can be sold. Apps that can be compelled by a court order to
        hand over everything you've ever written.
      </p>

      <p>
        The asymmetry is striking. We protect what we own, but not what we think. We
        protect our money, but not the messages we'd least want seen.
      </p>

      <h2>The case for self-custody of words</h2>

      <p>
        If you use an app that encrypts your data with a key only the company holds,
        you are trusting the company. That's a reasonable thing to do for some
        things — but not for the messages you most want to keep private.
      </p>

      <p>
        If you use an app that encrypts your data with a key only you hold, you are
        trusting the math. That's a different kind of trust — one that doesn't depend
        on a company's continued existence, integrity, or honesty.
      </p>

      <p>
        Self-custody of words is, in a sense, the same idea as self-custody of money.
        It's the recognition that some things should not be intermediated by a third
        party. That you should be the only one who can read them.
      </p>

      <h2>What changes when letters are encrypted</h2>

      <p>
        When you know that your message is genuinely private — that even tomorrowme
        cannot read it — the way you write changes. You can write the things you
        wouldn't write otherwise. The confession. The grief. The promise. The thing
        you've been carrying around for years.
      </p>

      <p>
        A letter that could be read by the company storing it is a different letter
        than one that cannot. The first is performance. The second is the truth.
      </p>

      <h2>What changes when letters are time-locked</h2>

      <p>
        The math also gives us something that wasn't possible before: time-lock. The
        ability to write something, seal it, and not be able to read it again until
        a specific future date — even if you want to.
      </p>

      <p>
        That's not a feature. That's a different relationship with yourself. The
        ability to send a message to who you are becoming, knowing you cannot cheat
        and read it early. The discipline of trust in your own future self.
      </p>

      <p>
        It's not for everyone. But for the people who want it, it changes something
        fundamental about what writing can be.
      </p>

      <h2>The default</h2>

      <p>
        The default for personal apps should be: your data is encrypted with a key
        only you hold. The default should be: the company can't read your messages,
        can't be compelled to read your messages, and can't sell what they can't read.
      </p>

      <p>
        Until that becomes the default, choose apps that make it a feature. Your
        letters deserve it.
      </p>
    </>
  );
}
